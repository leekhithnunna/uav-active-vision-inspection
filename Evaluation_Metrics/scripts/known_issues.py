"""Writes report/known_issues.md. Every number is read from repo files by this script."""
import csv
import glob
import json
import re
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, RESULTS, REPORT, RUN_DIRS  # noqa: E402


def csv_row(path, name, key="policy"):
    with open(path, newline="") as f:
        return next(r for r in csv.DictReader(f) if r[key] == name)


def readme_row(prefix):
    for line in (ROOT / "README.md").read_text(encoding="utf-8").splitlines():
        if line.startswith(prefix):
            return [c.strip() for c in line.strip("|").split("|")]
    return None


def tb_start(path):
    return int(re.search(r"tfevents\.(\d+)", path).group(1))


def main():
    out = ["# Known issues and mismatches", "",
           "Generated by `scripts/known_issues.py`; all values are read from the files named.", ""]

    # 1. README vs CSV for A2C learned detector
    r = readme_row("| A2C, learned detector")
    c = csv_row(RUN_DIRS["C_learned"] / "agentC_vs_baselines.csv", "A2C (Agent C)")
    keys = ["return_mean", "steps_mean", "defects_found_mean", "miou_mean", "energy_used_mean"]
    # a README cell agrees when it equals the CSV value rounded to the README's own number of decimals
    resolved = all(round(float(c[k]), len(v.split(".")[1]) if "." in v else 0) == float(v)
                   for k, v in zip(keys, r[1:6]))
    status = "RESOLVED: the README row now matches the CSV" if resolved else "the README row disagrees with the CSV"
    out += [f"## 1. Root README row 'A2C, learned detector' vs the CSV ({status})", "",
            "| Source | Return | Decisions | Defects | mIoU | Energy |", "|---|---|---|---|---|---|",
            f"| README.md (section 6, Agent C table) | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |",
            f"| For_Mukhesh/agentC_learned/agentC_vs_baselines.csv | {float(c['return_mean']):.2f} | "
            f"{float(c['steps_mean']):.2f} | {float(c['defects_found_mean']):.2f} | {float(c['miou_mean']):.3f} | "
            f"{float(c['energy_used_mean']):.3f} |", ""]
    if resolved:
        out += ["Resolved: the README row used to read 15.5 decisions and energy 0.40, probably from the first "
                "training run (see issue 2). It was corrected to the CSV values when Evaluation_Metrics was merged "
                "into main; the CSV is reproduced exactly by Phase 1 (see results/validation.csv).", ""]
    else:
        out += ["Decision: the CSV is trusted (it is reproduced exactly by Phase 1, see results/validation.csv). "
                "The README's own real-image table further down already uses the CSV values. The README row was "
                "probably written from the first training run (see issue 2).", ""]

    # 2. agentC_learned two TB runs
    d = RUN_DIRS["C_learned"]
    tbs = sorted(glob.glob(str(d / "tb" / "*" / "events*")))
    z = json.loads(zipfile.ZipFile(d / "best/best_model.zip").read("data"))
    best_start = int(z["start_time"]) / 1e9
    mon = json.loads(open(d / "monitor/0.monitor.csv").readline()[1:])["t_start"]
    out += ["## 2. For_Mukhesh/agentC_learned contains two training runs (tb/A2C_1 and tb/A2C_2)", "",
            "| Item | Unix time |", "|---|---|"]
    out += [f"| {Path(t).parent.name} event file | {tb_start(t)} |" for t in tbs]
    out += [f"| best/best_model.zip `start_time` | {best_start:.1f} |",
            f"| monitor/0.monitor.csv `t_start` | {mon:.1f} |", "",
            f"Verified: the saved best model, the monitor logs and therefore the CSV come from the SECOND run "
            f"({Path(tbs[-1]).parent.name}); start times agree within {abs(best_start - tb_start(tbs[-1])):.1f} s. "
            f"Training diagnostics for agentC_learned use {Path(tbs[-1]).parent.name} only.", ""]

    # 3. evaluations.npz has no success
    out += ["## 3. eval/evaluations.npz has no success array", "",
            "EvalCallback stores only timesteps, returns and episode lengths. The eval success-rate curves are "
            "computed from `monitor_eval.monitor.csv`, which has a `success` column (one row per eval episode, "
            "in eval-call order).", ""]

    # 4. single training seed
    seeds = sorted({json.load(open(p / "hyperparams.json"))["seed"] for p in RUN_DIRS.values()})
    out += ["## 4. Every original run used the same training seed", "",
            f"Training seeds found in hyperparams.json of all {len(RUN_DIRS)} runs: {seeds}. Variability across "
            "training seeds is measured only by the optional multi-seed runs in `multiseed_runs/`.", ""]

    # 5. Live_Demo save path
    out += ["## 5. Live_Demo `--save` writes into tracked files", "",
            "`demo_core/animate.py` saves to `Live_Demo/backup/gifs/<name>.gif` with a fixed name per demo, which "
            "would overwrite tracked backup GIFs. The videos are therefore rendered by importing the demos as a "
            "library and redirecting `demo_core.paths.out_dir` at runtime to `Evaluation_Metrics/videos/raw/`. "
            "No Live_Demo file is edited (checked by tests/test_eval.py).", ""]

    # 6. supervise-mode info fields
    out += ["## 6. Fields the environment does not report", "",
            "- `out_of_bounds` in `info` is a per-step flag and is always False in supervise/full modes (OOB moves "
            "inside an Explore option are not reported). `ScenarioEnv` counts them with a hook on `_nav_step`.",
            "- There is no battery-empty flag. It is derived as `battery <= 0` at episode end, which is exactly the "
            "env's own termination test (`self.battery <= 0`).",
            "- In supervise/full modes `steps` counts supervisor decisions; low-level steps are counted separately "
            "(`low_level_steps`).", "",
            "## 6b. The detector clip (V8) shows raw detector outputs, not the uncertainty the agents see", "",
            "Live_Demo's detector demo (`demos/d5_detector_views.py`) draws the per-pixel MC-dropout standard "
            "deviation as a heatmap and prints `u` = the raw mean predictive entropy (bits). On the q0 crack patch both "
            "are low although the crack is missed (false confidence). The environment does not use these raw values: "
            "`detector_cache.npz` stores the entropy rank-normalised to [0, 1] and made non-increasing in q (README "
            "section 5), so a blurred view always counts as uncertain. The `u` printed in V8 is therefore not the value "
            "the agents observe; the V8 voice-over explains this.", ""]

    # 7. scenario issues appended by evaluate_scenarios.py
    sk = RESULTS / "scenario_skips.csv"
    if sk.exists():
        rows = list(csv.DictReader(open(sk, newline="")))
        out += ["## 7. Scenario combinations skipped or limited", "", "| Scenario | Policy | Reason |", "|---|---|---|"]
        out += [f"| {r['scenario']} | {r['policy']} | {r['reason']} |" for r in rows] + [""]

    REPORT.mkdir(exist_ok=True)
    (REPORT / "known_issues.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", REPORT / "known_issues.md")


if __name__ == "__main__":
    main()
