"""Writes the Evaluation_Metrics blocks of the ROOT README.md from results/*.csv (no hand-typed numbers).

Two marked blocks are (re)generated in place:
  <!-- eval-metrics:section12 -->   ...   <!-- /eval-metrics:section12 -->   section 12 body
  <!-- eval-metrics:limitations --> ...   <!-- /eval-metrics:limitations --> one bullet in section 10
Everything outside the markers is left untouched.  `--check` exits 1 if the README is out of date.
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

EM = Path(__file__).resolve().parents[1]
ROOT = EM.parent
RESULTS = EM / "results"
README = ROOT / "README.md"
REPO_URL = "https://github.com/leekhithnunna/uav-active-vision-inspection"

# (group, policy in the CSVs, label in the README)
ROWS = [
    ("A", "DQN (Agent A)", "**Agent A, DQN**"),
    ("A", "raster_low", "raster_low (dense raster)"),
    ("B", "PPO (Agent B)", "**Agent B, PPO**"),
    ("B", "scripted_approach (upper bound)", "scripted_approach (upper bound)"),
    ("C", "A2C (Agent C)", "**Agent C, A2C**"),
    ("C", "rule_supervisor", "rule_supervisor"),
    ("C_withA", "A2C (C_withA)", "A2C with learned Agent A inside"),
    ("full", "ALL LEARNED (C + A + B)", "**All learned (C + A + B)**"),
    ("full", "ALL SCRIPTED (rule + raster + approach)", "All scripted"),
]
BATTERY = "S4_battery0.6"


def pct(x):
    return f"{100 * x:.0f} %"


def section12():
    s0 = pd.read_csv(RESULTS / "summary_S0_all.csv")
    gap = pd.read_csv(RESULTS / "robustness_gap.csv")
    gap = gap[gap.scenario == BATTERY]
    ms = pd.read_csv(RESULTS / "multiseed_per_seed.csv")
    sc = pd.read_csv(RESULTS / "scenario_summary.csv")
    scen = [s for s in dict.fromkeys(sc.scenario)]
    n = int(s0.n_episodes.iloc[0])
    seeds = s0.seeds.iloc[0].replace("-", "–")
    start_batt = BATTERY.split("battery")[1]

    out = [
        "`Evaluation_Metrics/` is the evaluation-metrics submission (MiniProject Demo). It reloads every trained "
        "model and saved training log in this repo (read only; nothing outside the folder is edited) and "
        f"recomputes all metrics on **held-out seeds {seeds}, n = {n} episodes per policy**, which none of the "
        f"agents saw during training. Each policy is run in the nominal task ({scen[0].split('_')[0]}) and in "
        f"{len(scen) - 1} varied environments ({scen[1].split('_')[0]}–{scen[-1].split('_')[0]}: real-image "
        "detector, defect density, "
        "observation noise, low starting battery, hard refine start); results carry 95 % confidence intervals. "
        f"Agents {', '.join(sorted(ms[ms.source == 'multiseed'].agent.unique()))} were retrained with extra "
        "training seeds to measure seed-to-seed variability. The folder also contains training diagnostics, "
        "plots, the generated report (Markdown / DOCX / PDF), ten narrated MP4 sessions and pytest checks that "
        "trace every reported number back to its CSV.",
        "",
        f"Key results (`Evaluation_Metrics/results/summary_S0_all.csv` and `robustness_gap.csv`; generated by "
        f"`Evaluation_Metrics/scripts/readme_section.py`, do not edit by hand):",
        "",
        f"| Policy | Success | Return (mean ± 95 % CI) | Energy used | Success at {pct(float(start_batt))} battery "
        f"| Battery empty at {pct(float(start_batt))} |",
        "|---|---|---|---|---|---|",
    ]
    for grp, pol, label in ROWS:
        r = s0[(s0.group == grp) & (s0.policy == pol)].iloc[0]
        g = gap[(gap.group == grp) & (gap.policy == pol)].iloc[0]
        out.append(f"| {label} | {pct(r.success_rate)} | {r.return_mean:.2f} ± {r.return_ci95:.2f} | "
                   f"{r.energy_used_mean:.3f} | {pct(g.success_perturbed)} | {pct(g.battery_empty_rate)} |")

    dqn = gap[(gap.group == "A") & (gap.policy == "DQN (Agent A)")].iloc[0]
    ras = gap[(gap.group == "A") & (gap.policy == "raster_low")].iloc[0]
    msum = pd.read_csv(RESULTS / "multiseed_summary.csv")
    seeds_txt = "; ".join(
        f"{r.agent}: return {r.return_mean:.3f} ± {r.return_std:.3f} (std), success {pct(r.success_mean)}"
        for r in msum.itertuples())
    out += [
        "",
        f"**Robustness finding.** With only {pct(float(start_batt))} starting battery the dense raster empties "
        f"the battery in {pct(ras.battery_empty_rate)} of missions (success {pct(ras.success_perturbed)}), "
        f"while the DQN still succeeds in {pct(dqn.success_perturbed)} (battery empty "
        f"{pct(dqn.battery_empty_rate)}), because battery is part of its observation and reward.",
        "",
        f"**Across training seeds** ({int(msum.n_seeds.iloc[0])} seeds each, held-out evaluation): {seeds_txt}.",
        "",
        "- Folder guide and how each metric is computed: [Evaluation_Metrics/README.md](Evaluation_Metrics/README.md)",
        "- Report: [Team08_Evaluation_Metrics.pdf](Evaluation_Metrics/report/Team08_Evaluation_Metrics.pdf) "
        "(also `.docx` and `.md` in `Evaluation_Metrics/report/`)",
        "- Videos: [video_index.md](Evaluation_Metrics/SUBMISSION/video_index.md)",
        "- Everything to upload: [Evaluation_Metrics/SUBMISSION/](Evaluation_Metrics/SUBMISSION/)",
        "",
        "Reproduce everything (evaluation, plots, videos, report, SUBMISSION folder and tests) with one command "
        "from the repo root:",
        "",
        "```bash",
        "python Evaluation_Metrics/run_all.py",
        "```",
    ]
    return "\n".join(out)


def limitations():
    ms = pd.read_csv(RESULTS / "multiseed_per_seed.csv")
    extra = ms[ms.source == "multiseed"]
    agents = sorted(extra.agent.unique())
    seeds = sorted(extra.train_seed.unique())
    orig = sorted(ms[ms.source == "original"].train_seed.unique())
    return (f"- The original runs each use a single training seed ({', '.join(map(str, orig))}). Multi-seed results "
            f"now exist for Agents {', '.join(agents)} (extra training seeds {', '.join(map(str, seeds))}, see "
            "`Evaluation_Metrics/results/multiseed_summary.csv`); the real-image, sensitivity, `agentC_withA` and "
            "integration runs are still single-seed.")


def replace_block(text, name, body):
    start, end = f"<!-- eval-metrics:{name} -->", f"<!-- /eval-metrics:{name} -->"
    i, j = text.find(start), text.find(end)
    if i < 0 or j < 0:
        raise SystemExit(f"README.md is missing the markers {start} ... {end}")
    return text[:i + len(start)] + "\n" + body + "\n" + text[j:]


def render(text):
    text = replace_block(text, "section12", section12())
    return replace_block(text, "limitations", limitations())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if README.md is not up to date")
    a = ap.parse_args()
    raw = README.read_bytes().decode("utf-8")
    nl = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    new = render(text)
    if a.check:
        if new != text:
            print("README.md evaluation-metrics blocks are out of date; run scripts/readme_section.py")
            sys.exit(1)
        print("README.md evaluation-metrics blocks are up to date")
        return
    README.write_bytes(new.replace("\n", nl).encode("utf-8"))
    print("updated", README)


if __name__ == "__main__":
    main()
